package salesian.university.helpers;

/**
 * A utility class to manage string transformations.
 */
public class StringManager {

    /**
     * This method converts the input string to lowercase.
     *
     * @param message the string to convert to lowercase.
     * @return the lowercase version of the input string.
     */
    public String getLowerCaseString(String message){
        return message.toLowerCase();
    }
}
